// tests/pbt.self-test.js
//
// Self-tests for the test harness itself (tests/vendor/assert.js and
// tests/vendor/pbt.js). These are NOT the real game correctness properties
// — those get added to their own *.test.js files alongside each pure
// module in later tasks. This file only proves the harness works: the
// assertion runner catches pass/fail correctly, and the PBT helper can
// generate, check, and shrink.

import { test, ok, equal, deepEqual, throws } from "./vendor/assert.js";
import { forAll, integer, array, string, boolean, oneOf, constant } from "./vendor/pbt.js";

// --- Assertion runner self-tests -------------------------------------------

test("assert.ok passes on truthy, throws on falsy", () => {
  ok(true);
  ok(1);
  ok("non-empty");
  throws(() => ok(false));
  throws(() => ok(0));
});

test("assert.equal passes on === match, throws on mismatch", () => {
  equal(2 + 2, 4);
  throws(() => equal(2 + 2, 5));
});

test("assert.deepEqual compares nested structures by value", () => {
  deepEqual({ a: [1, 2, { b: 3 }] }, { a: [1, 2, { b: 3 }] });
  throws(() => deepEqual({ a: 1 }, { a: 2 }));
});

// --- PBT helper self-tests --------------------------------------------------

// Feature: ai-detective, Harness self-check: integers generated by integer(min, max) stay within range
test("pbt integer() generates values within [min, max]", () => {
  const result = forAll(
    "integers stay in range",
    integer(-50, 50),
    (n) => n >= -50 && n <= 50,
    { iterations: 100, seed: 1 }
  );
  ok(result.pass, `expected pass, got: ${JSON.stringify(result)}`);
  equal(result.iterations, 100);
});

// Feature: ai-detective, Harness self-check: reversing an array twice returns the original array
test("pbt array() round-trips through double reverse", () => {
  const result = forAll(
    "double reverse is identity",
    array(integer(-10, 10), { minLength: 0, maxLength: 10 }),
    (arr) => {
      const twice = arr.slice().reverse().reverse();
      return JSON.stringify(twice) === JSON.stringify(arr);
    },
    { iterations: 100, seed: 42 }
  );
  ok(result.pass, `expected pass, got: ${JSON.stringify(result)}`);
});

// Feature: ai-detective, Harness self-check: string() generated length stays within bounds
test("pbt string() generates length within [minLength, maxLength]", () => {
  const result = forAll(
    "string length in bounds",
    string({ minLength: 2, maxLength: 8 }),
    (s) => s.length >= 2 && s.length <= 8,
    { iterations: 100, seed: 7 }
  );
  ok(result.pass, `expected pass, got: ${JSON.stringify(result)}`);
});

// Feature: ai-detective, Harness self-check: oneOf only produces values from its listed arbitraries
test("pbt oneOf() only produces one of the given constants", () => {
  const result = forAll(
    "oneOf stays within the given set",
    oneOf(constant("a"), constant("b"), constant("c")),
    (v) => v === "a" || v === "b" || v === "c",
    { iterations: 100, seed: 3 }
  );
  ok(result.pass, `expected pass, got: ${JSON.stringify(result)}`);
});

test("pbt boolean() only produces true or false", () => {
  const result = forAll(
    "boolean stays boolean",
    boolean(),
    (v) => v === true || v === false,
    { iterations: 100, seed: 99 }
  );
  ok(result.pass);
});

// This test deliberately uses a false property so we can prove that
// forAll(1) detects the failure and (2) shrinks it to a minimal
// counterexample. It registers as a passing harness test because we are
// asserting *about* the (expected) failed property result, not asserting
// the property itself held.
test("pbt forAll detects a failing property and shrinks to a minimal counterexample", () => {
  const result = forAll(
    "all integers are less than 10 (deliberately false)",
    integer(0, 1000),
    (n) => n < 10,
    { iterations: 100, seed: 123 }
  );
  ok(!result.pass, "expected the deliberately-false property to fail");
  ok(
    typeof result.counterexample === "number",
    "expected a numeric counterexample"
  );
  // The minimal counterexample for "n < 10" over integers generated with a
  // floor at 0 should shrink all the way down to exactly 10.
  equal(result.counterexample, 10);
});

test("pbt forAll is reproducible for a given seed", () => {
  const run1 = forAll("repeatable", integer(0, 1000), (n) => n < 10, {
    iterations: 100,
    seed: 123,
  });
  const run2 = forAll("repeatable", integer(0, 1000), (n) => n < 10, {
    iterations: 100,
    seed: 123,
  });
  deepEqual(run1.counterexample, run2.counterexample);
});
